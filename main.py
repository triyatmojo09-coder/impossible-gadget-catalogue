def output_path():
    target = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output/entry.png")
    if not os.path.isdir(target) and target.lower().endswith((".png", ".jpg", ".jpeg")):
        return target
    return os.path.join(target, "entry.png")


def main():
    path = output_path()
    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(base64.b64decode(_IMAGE_B64))
    return 0


